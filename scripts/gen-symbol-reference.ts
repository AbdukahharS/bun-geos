/**
 * Generate docs/reference/symbols.md — the JS API ↔ geos_c symbol mapping
 * table (decisions.md open item #3, closed in Phase 5 M5). Mechanical from
 * src/symbols.ts so it cannot drift; `bun run docs:reference` regenerates,
 * and the freshness test (test/unit/reference.test.ts) fails when a bound
 * symbol lacks a reference entry.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { GEOS_TABLE, SHIM_TABLE } from "../src/symbols.ts";

const ROOT = join(import.meta.dir, "..");

/** Binding-rule annotations per symbol group (kept in sync with the table's
 * section comments and the F10/F6 house rules). */
const RULES: Array<{ match: RegExp; note: string }> = [
  {
    match: /^geos_shim_init|geos_shim_finish|geos_shim_context/,
    note: "context lifecycle (D3/D4)",
  },
  {
    match: /^geos_shim_last_error|geos_shim_last_notice/,
    note: "thread-local capture; cstring return — no free (F10 rule 2)",
  },
  { match: /^geos_shim_build_/, note: "batch/loop builders; GEOS consumes inputs even on failure" },
  {
    match: /^geos_shim_destroy_many/,
    note: "arena teardown: frees geoms AND the shim-owned pointer array",
  },
  { match: /^geos_shim_clone_/, note: "owned clones (D21)" },
  { match: /^geos_shim_union_all|geos_shim_coverage_union/, note: "strategy dispatch (D20)" },
  {
    match: /^geos_shim_.*_pred_all/,
    note: "batch masks, 0 ok / 1 exception / 2 interrupted (D18)",
  },
  { match: /^geos_shim_relate_pattern_all/, note: "batch DE-9IM (D18)" },
  {
    match: /^geos_shim_strtree_insert_all/,
    note: "batch insert, 0 ok / 1 invalid-args; continues the id sequence (D32)",
  },
  { match: /^geos_shim_strtree_/, note: "1-based id items (D16); nearest via bound id→geom table" },
  { match: /^geos_shim_overlay_all/, note: "8-op id table (D22); grid for *_PREC" },
  { match: /^geos_shim_unary_all/, note: "9-op id table (D27); d1..d4 carry scalar params" },
  { match: /^geos_shim_binary_all/, note: "2-op id table (D27); d1 = snap tolerance" },
  { match: /^geos_shim_measure_all/, note: "5-op id table (D22)" },
  { match: /^geos_shim_buffer_all/, note: "caller-built params (D22)" },
  {
    match: /^geos_shim_read_wkb_many/,
    note: "byte offsets (the one byte-offset family); u32 caps at 4 GB; D31 linear check rides the crossing",
  },
  { match: /^geos_shim_num_points_many/, note: "type-generic vertex counts (D23 chunking)" },
  { match: /^geos_shim_heap_bytes/, note: "D24 accounting" },
  { match: /^geos_shim_interrupt_/, note: "atomic GLOBAL flag (D19)" },
  {
    match: /WKTWriter|WKBWriter|GeoJSONWriter/,
    note: "writer options; `ptr` return → CString + GEOSFree_r (F10 rule 3)",
  },
  {
    match: /WKTReader_read|WKBReader_read|GeoJSONReader/,
    note: "parsers; failed ptr returns are JS null (F6)",
  },
  {
    match: /CoordSeq_copyFromBuffer|CoordSeq_copyToBuffer/,
    note: "the D9 golden path — interleaved f64 buffers",
  },
  { match: /_r$/, note: "" },
];

function ruleFor(name: string): string {
  for (const r of RULES) {
    if (r.match.test(name) && r.note !== "") return r.note;
  }
  return "";
}

function argsOf(args: readonly string[]): string {
  return args.join(", ");
}

const lines: string[] = [
  "# Symbol reference — JS bindings ↔ `geos_c`",
  "",
  "> GENERATED by `scripts/gen-symbol-reference.ts` (`bun run docs:reference`) from",
  "> `src/symbols.ts` — do not edit by hand; the freshness test fails on drift.",
  "> Binding rules (D15/F6/F10): `const char*` ARGS → `cstring`; GEOS-owned string",
  "> returns → `ptr` + `CString` view + `GEOSFree_r` (a `cstring` return leaks);",
  "> char returns mask `& 0xff`; INT returns (orientPolygons, minimumClearance,",
  "> grid fractions, strtree nearest) are NOT masked; failed `ptr` returns are JS",
  "> `null`, never `0`.",
  "",
  `## Shim exports (${Object.keys(SHIM_TABLE).length})`,
  "",
  "| symbol | args | returns | notes |",
  "|--------|------|---------|-------|",
];

for (const [name, spec] of Object.entries(SHIM_TABLE)) {
  lines.push(`| \`${name}\` | ${argsOf(spec.args)} | ${spec.returns} | ${ruleFor(name)} |`);
}

lines.push(
  "",
  `## geos_c bindings (${Object.keys(GEOS_TABLE).length})`,
  "",
  "| symbol | args | returns | notes |",
  "|--------|------|---------|-------|",
);

for (const [name, spec] of Object.entries(GEOS_TABLE)) {
  lines.push(`| \`${name}\` | ${argsOf(spec.args)} | ${spec.returns} | ${ruleFor(name)} |`);
}

lines.push("");

const dest = join(ROOT, "docs", "reference", "symbols.md");
writeFileSync(dest, lines.join("\n"));
console.log(
  `written: docs/reference/symbols.md (${Object.keys(SHIM_TABLE).length} shim + ${Object.keys(GEOS_TABLE).length} geos_c symbols)`,
);
